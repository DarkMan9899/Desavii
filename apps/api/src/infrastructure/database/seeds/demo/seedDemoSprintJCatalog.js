async function resolveAmenityIds(connection, names) {
  if (names.length === 0) return [];
  const [rows] = await connection.query(
    'SELECT id FROM listing_amenities WHERE name IN (?)',
    [names],
  );
  return rows.map((row) => row.id);
}

async function createUser(connection, ctx, { email, fullName }) {
  const [firstName, ...rest] = fullName.split(' ');
  const lastName = rest.join(' ') || firstName;
  const passwordHash = await argon2.hash(DEMO_PASSWORD);
  const normalizedEmail = email.trim().toLowerCase();
  const [result] = await connection.query(
    `INSERT INTO users
      (email, normalized_email, password_hash, first_name, last_name, status_id,
       is_email_verified, email_verified_at, preferred_language_id, preferred_currency_id)
     VALUES (?, ?, ?, ?, ?, ?, 1, UTC_TIMESTAMP(3), ?, ?)`,
    [
      email,
      normalizedEmail,
      passwordHash,
      firstName,
      lastName,
      ctx.activeStatusId,
      ctx.enLanguageId,
      ctx.amdCurrencyId,
    ],
  );
  const userId = result.insertId;
  await connection.query(
    'INSERT IGNORE INTO role_user (role_id, user_id) VALUES (?, ?)',
    [ctx.customerRoleId, userId],
  );
  return userId;
}

async function createPartner(connection, ctx, spec) {
  const ownerUserId = await createUser(connection, ctx, {
    email: spec.email,
    fullName: spec.displayName,
  });
  const [result] = await connection.query(
    `INSERT INTO partners
      (legal_name, display_name, slug, email, verification_status_id, moderation_status_id, owner_user_id)
     VALUES (?, ?, ?, ?, ?, ?, ?)`,
    [
      spec.legalName,
      spec.displayName,
      spec.slug,
      spec.email,
      ctx.approvedStatusId,
      ctx.approvedStatusId,
      ownerUserId,
    ],
  );
  const partnerId = result.insertId;
  // eslint-disable-next-line no-restricted-syntax -- seeding must run in a stable, readable order
  for (const [localeCode, description] of Object.entries(spec.translations)) {
    // eslint-disable-next-line no-await-in-loop -- sequential by design
    await connection.query(
      'INSERT INTO partner_translations (partner_id, language_id, description) VALUES (?, ?, ?)',
      [partnerId, ctx.languageIds.get(localeCode), description],
    );
  }
  await connection.query(
    'INSERT INTO partner_employees (partner_id, user_id, role_id) VALUES (?, ?, ?)',
    [partnerId, ownerUserId, ctx.ownerRoleId],
  );
  return { partnerId, ownerUserId };
}

