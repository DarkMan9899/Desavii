/**
 * Sprint J — Final Realistic Marketplace Data.
 *
 * Adds exactly 3 hand-authored, materially non-clone, fully tri-lingual
 * (EN/HY/RU) listings to every one of the 9 public categories (27 total),
 * each owned by one of 8 fresh demo partners. Deliberately self-contained:
 * unlike `seedDemoInventoryScenarios.js`/`seedDemoListingRichContent.js`
 * (which build on the dev-vendor partner `seedAll()` already creates),
 * this module has NO dependency on `seedDemoMarketplace.js` or either of
 * those two files — it only needs the plain `seedAll()` baseline
 * (categories/listing_types/bookable_unit_types/pricing_models/cities/
 * amenities/policy_definitions/currencies/languages), so it can be
 * exercised on its own by a focused, fast integration test instead of
 * paying for the full ~80-listing/150-booking demo pipeline every run.
 *
 * Root cause this addresses: before Sprint J, `seedAll()` seeds zero
 * marketplace listings, and the only listing-bearing seed layer
 * (`seedDemoMarketplace.js`) covers just 5 of the 9 categories with
 * titles generated by interpolating one shared description template with
 * an adjective+city pair — real city variety, but not materially
 * different businesses, and English-only. This module is what a category
 * page actually needs to look and read like a real, launch-ready
 * marketplace category.
 *
 * Reuses this `demo/` family's own established primitives rather than
 * re-implementing them (CLAUDE.md "never duplicate functionality"):
 * `insertListing`/`insertBookableUnit`/`seedCalendarWindow` from
 * `seedDemoInventoryScenarios.js`, and `upsertTranslation`/
 * `insertPolicyValue` from `seedDemoListingRichContent.js`.
 * Like both of those, every write here is a plain INSERT (safe because
 * this only ever runs — via `cli/seedDemo.js`/`cli/seedDemoDev.js` or a
 * test's own `up()+seedAll()` — against a just-recreated database).
 *
 * No dynamic attribute values (`listing_attribute_values_*`) are written
 * — those are optional, category-scoped Generic Attribute Engine detail,
 * not part of Sprint J's required "meaningful listing" checklist (title,
 * description, location, pricing, availability, amenities, policies,
 * media, published state — CLAUDE.md Sprint J spec §7). Phase 18 rich
 * content (highlights/itinerary/FAQs) is likewise intentionally not
 * authored here for all 27 — that tier already exists for the 6
 * `seedDemoInventoryScenarios.js` flagships, and duplicating that depth
 * across 27 more listings would be exactly the "inflate content beyond
 * what's needed" Sprint J's own spec (§31, §51) warns against.
 */

